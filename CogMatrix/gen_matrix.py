"""Generate ../notes/MATRIX.md from the cells in CogMatrix/Matrix/*.lean.

A cell is a theorem named after a law (`certainty`) when the family has the
law, or `not_<law>` when it lacks it. Run from CogMatrix/.

Every cell is also checked with `#print axioms`. A cell that depends on
`sorryAx` or on any axiom beyond Lean's standard three is marked **unproved**
in the matrix, and the script exits with an error.
"""
import re, pathlib, json, subprocess, sys, tempfile

STANDARD_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}

LAWS = ["certainty", "stability", "orderFree", "recency", "storedOnly", "determinate"]
LAW_NAMES = {"certainty": "Certainty", "stability": "Stability",
             "orderFree": "Order-freedom", "recency": "Recency",
             "storedOnly": "Stored-only", "determinate": "Determinate"}
FAMILIES = [("Discrimination", "Discrimination (EPAM)"),
            ("Activation", "Activation (ACT-R, d = 1, s = 1)"),
            ("Strength", "Strength with a criterion (DOA)"),
            ("Minerva", "Global matching (MINERVA 2)")]

cells = {}
for fam, _ in FAMILIES:
    src = pathlib.Path(f"CogMatrix/Matrix/{fam}.lean").read_text()
    for m in re.finditer(r"^theorem (not_)?(\w+)", src, re.M):
        neg, law = m.group(1), m.group(2)
        if law in LAWS:
            cells[(fam, law)] = ("lacks" if neg else "has", f"`{fam}.{(neg or '') + law}`")

# Check each cell's axioms against a fresh build.
build = subprocess.run(["lake", "build"], capture_output=True, text=True)
if build.returncode:
    sys.exit("lake build failed; fix the build before generating the matrix:\n" + build.stdout[-3000:] + build.stderr[-1000:])
names = {k: f"Cog.Matrix.{k[0]}.{v[1].split('.', 1)[1].strip('`')}" for k, v in cells.items()}
with tempfile.TemporaryDirectory() as d:
    f = pathlib.Path(d, "Axioms.lean")
    f.write_text("import CogMatrix\n" + "".join(f"#print axioms {n}\n" for n in names.values()))
    res = subprocess.run(["lake", "env", "lean", str(f)], capture_output=True, text=True)
report = res.stdout + res.stderr
axioms = {}
for k, n in names.items():
    m = re.search(rf"'{re.escape(n)}' (does not depend on any axioms|depends on axioms: \[([^\]]*)\])", report)
    if not m:
        sys.exit(f"no axiom report for {n}:\n{report}")
    axioms[k] = {a.strip() for a in (m.group(2) or "").split(",") if a.strip()}
unproved = {k: sorted(a - STANDARD_AXIOMS) for k, a in axioms.items() if a - STANDARD_AXIOMS}

out = ["# The theory matrix", "",
       "Generated by `gen_matrix.py` from `CogMatrix/Matrix/*.lean`; do not edit.", "",
       "Each cell is a theorem: **has** (a general proof, under the family's stated conditions) "
       "or **lacks** (a counterexample). Theorem names are in `Cog.Matrix`.", "",
       "| Family | " + " | ".join(LAW_NAMES[l] for l in LAWS) + " |",
       "|---|" + "---|" * len(LAWS)]
for fam, title in FAMILIES:
    row = []
    for l in LAWS:
        v = cells.get((fam, l))
        if not v:
            row.append("open")
        elif (fam, l) in unproved:
            row.append(f"**unproved** ({v[0]}?) {v[1]}, uses {', '.join(unproved[(fam, l)])}")
        else:
            row.append(f"**{v[0]}** {v[1]}")
    out.append(f"| {title} | " + " | ".join(row) + " |")
out += ["", "Every cell is checked with `#print axioms` when this file is generated: "
        + ("each depends only on Lean's standard axioms (`propext`, `Classical.choice`, `Quot.sound`), "
           "so none uses `sorry`." if not unproved else
           f"{len(unproved)} cell(s) depend on `sorry` or a non-standard axiom and are marked **unproved**.")]
missing = [(f, l) for f, _ in FAMILIES for l in LAWS if (f, l) not in cells]
out += ["", "Every law is had by some family and lacked by another." if not missing
        and all(len({cells[(f, l)][0] for f, _ in FAMILIES}) == 2 for l in LAWS)
        else "Some laws do not yet discriminate, or have open cells."]
rows = {}
for fam, title in FAMILIES:
    rows.setdefault(tuple(cells.get((fam, l), ("open",))[0] for l in LAWS), []).append(title)
same = [ts for ts in rows.values() if len(ts) > 1]
out += ["", "Every family has its own row." if not same else
        "Families the laws do not separate: " + "; ".join(", ".join(ts) for ts in same) + "."]
ev = json.loads(pathlib.Path("evidence.json").read_text())
out += ["", "## Against the evidence about people", "",
        "This row is different in kind from the theorem cells above. It is a judgment of what experiments "
        "show about people, from `evidence.json`, with sources below. A family **fits** a law when its cell "
        "agrees with the evidence; `mixed` evidence counts neither way.", "",
        "| | " + " | ".join(LAW_NAMES[l] for l in LAWS) + " |",
        "|---|" + "---|" * len(LAWS),
        "| People | " + " | ".join(f"*{ev[l]['status']}*" for l in LAWS) + " |", "",
        "| Family | Fits | Conflicts with the evidence on |", "|---|---|---|"]
settled = [l for l in LAWS if ev[l]["status"] in ("has", "lacks")]
for fam, title in FAMILIES:
    bad = [LAW_NAMES[l] for l in settled if cells[(fam, l)][0] != ev[l]["status"]]
    out.append(f"| {title} | {len(settled) - len(bad)} of {len(settled)} | {', '.join(bad) or 'none'} |")
fits = [t for f, t in FAMILIES if all(cells[(f, l)][0] == ev[l]["status"] for l in settled)]
out += ["", ("Families consistent with all the evidence judged settled: " + "; ".join(fits) + ".") if fits
        else "No family is consistent with all the evidence judged settled.",
        "", "Each judgment rests on a bridge from what an experiment measures (reports, decisions) to what a law "
        "is about (what memory retrieves). The bridges are stated below and are not formalized, so a fit here is a "
        "hypothesis, not a result."]
out += ["", "### Evidence", ""]
for l in LAWS:
    out.append(f"- **{LAW_NAMES[l]}** (*{ev[l]['status']}*). {ev[l]['summary']} *Bridge:* {ev[l]['bridge']}")
    for src in ev[l]["sources"]:
        out.append(f"  - {src}")
pathlib.Path("../notes/MATRIX.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
if unproved:
    sys.exit("unproved cells: " + ", ".join(names[k] for k in unproved))
