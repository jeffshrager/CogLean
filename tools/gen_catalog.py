#!/usr/bin/env python3
"""Generate notes/CATALOG.md: every theorem in every package, read from Lean.

For each package, a temporary file imports the package and runs
tools/catalog_meta.lean, which reports, for each theorem: whether it is
quantified (general) or closed (a single computed case); whether its
conclusion is a theory-neutral law from CogLib.Phenomena, or the negation of
one; whether it uses only the standard axioms; and its docstring.

Run from the repository root: python3 tools/gen_catalog.py
"""
import os, re, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKAGES = [  # directory, import root, module prefixes, title
    ("CogLib", "CogLib", ["CogLib"], "CogLib: the general library"),
    ("EPAM", "Epam", ["Epam"], "EPAM: discrimination nets"),
    ("StrategyChoice", "StrategyChoice", ["StrategyChoice"], "Strategy choice: distributions of associations"),
    ("MultiDigit", "MultiDigit", ["MultiDigit"], "Multi-digit addition (with the problem solver)"),
    ("CogMatrix", "CogMatrix", ["CogMatrix"], "The theory matrix: memory families against retrieval laws"),
    ("Experiments", "Experiments", ["Experiments"], "Experiments written against the memory interface"),
    ("Concepts", "Concepts", ["Concepts"], "Concepts: selective modification and threshold membership"),
    ("SemanticMemory", "SemanticMemory", ["SemanticMemory"], "Semantic memory: hierarchical networks and feature comparison"),
    ("ViewApplication", "ViewApplication", ["ViewApplication"], "View application and view selection"),
]
ENV = dict(os.environ, PATH=os.path.expanduser("~/.elan/bin") + ":" + os.environ["PATH"])
META = open(os.path.join(ROOT, "tools", "catalog_meta.lean")).read()


def run_package(d, imp, prefixes):
    r = subprocess.run(["lake", "build"], cwd=os.path.join(ROOT, d), env=ENV, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"{d}: lake build failed:\n{r.stdout[-2000:]}{r.stderr[-2000:]}")
    pref = ", ".join(f"`{p}" for p in prefixes)
    src = f"import Lean\nimport {imp}\n{META}\n#eval show Lean.Meta.MetaM Unit from catLine [{pref}]\n"
    with tempfile.NamedTemporaryFile("w", suffix=".lean", delete=False, dir=os.path.join(ROOT, d)) as f:
        f.write(src)
        path = f.name
    try:
        r = subprocess.run(["lake", "env", "lean", path], cwd=os.path.join(ROOT, d), env=ENV,
                           capture_output=True, text=True)
    finally:
        os.unlink(path)
    if r.returncode != 0:
        sys.exit(f"{d}: catalog failed:\n{r.stdout[-3000:]}{r.stderr[-3000:]}")
    rows = []
    for line in r.stdout.splitlines():
        parts = line.split("|", 8)
        if len(parts) != 9:
            continue
        name, mod, q, neg, law, lawmod, ok, assumed, doc = parts
        rows.append(dict(name=name, mod=mod, q=q == "true", neg=neg == "true", law=law,
                         lawmod=lawmod, ok=ok == "true",
                         assumed=[a for a in assumed.split(",") if a], doc=doc.strip()))
    return rows


def first_sentence(doc):
    doc = doc.strip()
    m = re.match(r"(.+?\.)(\s+[A-Z*`(]|$)", doc)
    s = m.group(1) if m else doc
    return s if len(s) <= 200 else s[:197] + "..."


def short(n):
    return n.split(".")[-1]


def main():
    out = ["# Catalog: what is proved, module by module", "",
           "Generated by `tools/gen_catalog.py` from the Lean environment; do not edit by hand.", "",
           "How to read it:",
           "- **Laws** are theory-neutral phenomena defined once in `CogLib.Phenomena` (retrieval laws, verification laws, phenomena of learning and of combination). A theorem whose conclusion is a law, or its negation, says that a theory has the law, or lacks it.",
           "- **General** theorems bind variables: they hold for every value of them (every net, every problem, every number, or every parameter setting), under the hypotheses stated. **Instances** are closed statements, single cases computed exactly. \"General\" here is coarser than the theory matrix's \"every setting\": a theorem for every number at fixed parameters is general here. The law verdicts follow the matrix's words (has / never for general, can hold / lacks for instances) in this coarser sense.",
           "- **Headline** theorems are those whose docstrings begin in bold; the rest are lemmas.",
           "- **Given**: the laws or phenomena among a theorem's hypotheses. A theorem with none *derives* its conclusion from mechanisms and conditions; one with some is *conditional* on them (a relation between phenomena, or a result for any memory with those laws). This is read from the statement; whether the remaining premises are independently motivated is a scientific judgment (see `EXPLANATORY_AUDIT.md`).",
           "- Every theorem listed uses only Lean's standard axioms unless marked otherwise; none uses `sorry`.", ""]
    totals = []
    bad = []
    for d, imp, prefixes, title in PACKAGES:
        print(f"{d}...", file=sys.stderr)
        rows = run_package(d, imp, prefixes)
        rows = [r for r in rows if not r["name"].startswith("_")]
        law_rows = [r for r in rows if r["lawmod"].startswith("CogLib.Phenomena")]
        cond_rows = [r for r in rows if r["assumed"]]
        head = [r for r in rows if r["doc"].startswith("**")]
        gen = sum(r["q"] for r in rows)
        totals.append((title, len(rows), gen, len(rows) - gen, len(law_rows), len(cond_rows), len(head)))
        bad += [r["name"] for r in rows if not r["ok"]]
        out += [f"## {title}", "",
                f"{len(rows)} theorems: {gen} general, {len(rows) - gen} instances; {len(head)} headline; {len(law_rows)} about laws; {len(cond_rows)} conditional on laws.", ""]
        if law_rows:
            out += ["**Laws**", "", "| Theorem | Law | Verdict | Scope | Given |", "|---|---|---|---|---|"]
            for r in sorted(law_rows, key=lambda r: (r["law"], r["name"])):
                verdict = ("lacks" if not r["q"] else "never") if r["neg"] else ("has" if r["q"] else "can hold")
                scope = "general" if r["q"] else "instance"
                given = ", ".join(short(a) for a in r["assumed"]) or "derived"
                out.append(f"| `{r['name']}` | {short(r['law'])} | {verdict} | {scope} | {given} |")
            out.append("")
        if head:
            out += ["**Headline theorems**", "", "| Theorem | Scope | Given | Statement |", "|---|---|---|---|"]
            for r in sorted(head, key=lambda r: (r["mod"], r["name"])):
                stmt = first_sentence(r["doc"]).replace("**", "")
                given = ", ".join(short(a) for a in r["assumed"]) or "—"
                out.append(f"| `{r['name']}` | {'general' if r['q'] else 'instance'} | {given} | {stmt} |")
            out.append("")
    out += ["## Totals", "", "| Package | Theorems | General | Instances | About laws | Conditional on laws | Headline |", "|---|---|---|---|---|---|---|"]
    for t in totals:
        out.append("| " + " | ".join(str(x) for x in t) + " |")
    out.append("| **All** | " + " | ".join(str(sum(t[i] for t in totals)) for i in range(1, 7)) + " |")
    out.append("")
    if bad:
        out += ["## Non-standard axioms", ""] + [f"- `{b}`" for b in bad] + [""]
    with open(os.path.join(ROOT, "notes", "CATALOG.md"), "w") as f:
        f.write("\n".join(out))
    print("\n".join(out[-(len(totals) + 6):]))
    if bad:
        sys.exit(f"{len(bad)} theorems use non-standard axioms")


if __name__ == "__main__":
    main()
