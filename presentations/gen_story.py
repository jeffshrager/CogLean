"""Generate coglean-story.tex: the core slide of each of the other five decks,
copied verbatim with its notes, in an order that tells the story in one talk.
Run from presentations/ (the Makefile does)."""
import re

PICKS = [
    ("coglean-overview.tex", "Three kinds of evidence a theory can give",
     "Why prove things about cognitive theories at all."),
    ("recognition-retrieval.tex", "Confident errors",
     "What gets proved: a prediction that neither EPAM nor the distributions-of-associations "
     "model makes alone, holding for every parameter setting. (Full talk: recognition-retrieval.)"),
    ("recognition-retrieval-lean.tex", "Confident errors: the proof is a composition",
     "How it is proved: the actual Lean proof is five lines, because the work is factored into "
     "general lemmas below it. (Full talk: recognition-retrieval-lean.)"),
    ("blind-simulation.tex", "Results: no failures",
     "Is the formalization faithful? A Python simulator written blind from a prose specification, "
     "against predictions preregistered before it existed. (Full talk: blind-simulation.)"),
    ("laws-matrix-experiments.tex", "The matrix",
     "Where it goes: instead of formalizing models one by one, laws of memory, and a matrix of "
     "which families have which law, every cell a theorem. Experiments can then be derived from "
     "laws that disagree. (Full talk: laws-matrix-experiments.)"),
]

HEAD = r"""\documentclass[aspectratio=169,11pt]{beamer}
\input{preamble}
\input{leancode}

% Generated by gen_story.py from the other five decks; do not edit. The core
% slide of each, copied verbatim, in an order that tells the story in one talk.

\title{CogLean in five slides}
\subtitle{Why prove, what is proved, how, is it faithful, and where it goes}
\author{Jeff Shrager}
\date{October 2026}

\begin{document}

\begin{frame}
  \titlepage
\end{frame}
\note{
\begin{itemize}
\item One straight-through talk: the core slide from each of the five CogLean decks. Each slide's notes begin with the transition, then the original notes.
\end{itemize}
}
"""


def grab(fname, title):
    s = open(fname).read()
    m = re.search(r"\\begin\{frame\}(\[fragile\])?\{" + re.escape(title) + r"\}", s)
    assert m, (fname, title)
    j = s.index("\\end{frame}", m.start()) + len("\\end{frame}")
    frame, rest = s[m.start():j], s[j:]
    note = ""
    if rest.lstrip().startswith("\\note{"):
        start = rest.index("\\note{")
        note = rest[start:rest.index("\n}\n", start) + 3]
    return frame, note


out = [HEAD]
for fname, title, trans in PICKS:
    frame, note = grab(fname, title)
    if note:
        note = note.replace("\\note{\n\\begin{itemize}",
                            "\\note{\n\\textbf{Transition.} " + trans + "\n\\begin{itemize}", 1)
    else:
        note = "\\note{\n\\textbf{Transition.} " + trans + "\n}\n"
    out.append("\n" + frame + "\n" + note)
out.append("\n\\end{document}\n")
open("coglean-story.tex", "w").write("".join(out))
